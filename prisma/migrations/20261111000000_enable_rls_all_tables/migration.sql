-- Enable Row Level Security (RLS) on all tables in the public schema with NO public policies.
-- Why: Supabase exposes the `public` schema via PostgREST (`anon` and `authenticated` roles) by default.
-- Enabling RLS without any public policies blocks all direct client/PostgREST access while allowing
-- our Node.js backend (which connects via Prisma using the `postgres` role with BYPASSRLS privilege)
-- full access to manage data securely.

DO $$
DECLARE
  r RECORD;
BEGIN
  FOR r IN (
    SELECT tablename
    FROM pg_tables
    WHERE schemaname = 'public'
      AND tablename NOT LIKE '_prisma%'
  ) LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', r.tablename);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated;', r.tablename);
  END LOOP;
END $$;

