export function getLanguageDetails(code?: string | null): LanguageInfo {
  const normalized = (code || 'en').trim().toLowerCase().split('-')[0];
  return (
    languageMap.get(normalized) ?? {
      code: 'en',
      name: 'English',
      nativeName: 'English',
      direction: 'ltr',
      locale: 'en-US',
      region: 'Global',
    }
  );
}

export function getTranslationsForLanguage(code?: string | null): Record<string, string> {
  const info = getLanguageDetails(code);
  return {
    ...POS_TRANSLATIONS.en,
    ...(POS_TRANSLATIONS[info.code] ?? {}),
  };
}

